CREATE SCHEMA douyin;

REVOKE ALL ON SCHEMA douyin FROM PUBLIC, anon, authenticated, service_role;

CREATE TABLE douyin."USER" (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    phone VARCHAR(32) COLLATE "C" NOT NULL,
    nickname VARCHAR(80) NOT NULL,
    account_status VARCHAR(16) COLLATE "C" NOT NULL DEFAULT 'ACTIVE',
    registered_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (user_id),
    CONSTRAINT uq_user_phone UNIQUE (phone),
    CONSTRAINT ck_user_phone CHECK (CHAR_LENGTH(TRIM(phone)) > 0 AND OCTET_LENGTH(phone) = OCTET_LENGTH(TRIM(phone)) AND OCTET_LENGTH(phone) = CHAR_LENGTH(phone)),
    CONSTRAINT ck_user_status CHECK (account_status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_user_id CHECK (user_id > 0)
);

CREATE TABLE douyin."MUSIC" (
    music_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title VARCHAR(200) NOT NULL,
    artist_name VARCHAR(200) NOT NULL,
    audio_url VARCHAR(2048) NOT NULL,
    PRIMARY KEY (music_id),
    CONSTRAINT ck_music_id CHECK (music_id > 0)
);

CREATE TABLE douyin."TOPIC" (
    topic_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    topic_name VARCHAR(100) COLLATE "C" NOT NULL,
    PRIMARY KEY (topic_id),
    CONSTRAINT uq_topic_name UNIQUE (topic_name),
    CONSTRAINT ck_topic_name CHECK (CHAR_LENGTH(TRIM(topic_name)) > 0 AND OCTET_LENGTH(topic_name) = OCTET_LENGTH(TRIM(topic_name))),
    CONSTRAINT ck_topic_id CHECK (topic_id > 0)
);

CREATE TABLE douyin."VIDEO" (
    video_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    creator_id BIGINT NOT NULL,
    music_id BIGINT NULL,
    caption VARCHAR(2000) NOT NULL DEFAULT '',
    media_url VARCHAR(2048) NOT NULL,
    duration_seconds DECIMAL(9,3) NOT NULL,
    visibility_status VARCHAR(16) COLLATE "C" NOT NULL DEFAULT 'PUBLISHED',
    published_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (video_id),
    CONSTRAINT fk_video_creator FOREIGN KEY (creator_id) REFERENCES douyin."USER" (user_id),
    CONSTRAINT fk_video_music FOREIGN KEY (music_id) REFERENCES douyin."MUSIC" (music_id),
    CONSTRAINT ck_video_duration CHECK (duration_seconds > 0),
    CONSTRAINT ck_video_status CHECK (visibility_status IN ('PUBLISHED', 'HIDDEN')),
    CONSTRAINT ck_video_id CHECK (video_id > 0)
);

CREATE TABLE douyin."COMMENT" (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    video_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    parent_comment_id BIGINT NULL,
    body_text TEXT NOT NULL,
    comment_status VARCHAR(16) COLLATE "C" NOT NULL DEFAULT 'VISIBLE',
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (comment_id),
    CONSTRAINT fk_comment_video FOREIGN KEY (video_id) REFERENCES douyin."VIDEO" (video_id),
    CONSTRAINT fk_comment_author FOREIGN KEY (author_id) REFERENCES douyin."USER" (user_id),
    CONSTRAINT fk_comment_parent FOREIGN KEY (parent_comment_id) REFERENCES douyin."COMMENT" (comment_id),
    CONSTRAINT ck_comment_body CHECK (CHAR_LENGTH(TRIM(body_text)) > 0),
    CONSTRAINT ck_comment_status CHECK (comment_status IN ('VISIBLE', 'HIDDEN')),
    CONSTRAINT ck_comment_id CHECK (comment_id > 0)
);

CREATE TABLE douyin."VIDEO_TOPIC" (
    video_id BIGINT NOT NULL,
    topic_id BIGINT NOT NULL,
    tagged_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (video_id, topic_id),
    CONSTRAINT fk_video_topic_video FOREIGN KEY (video_id) REFERENCES douyin."VIDEO" (video_id),
    CONSTRAINT fk_video_topic_topic FOREIGN KEY (topic_id) REFERENCES douyin."TOPIC" (topic_id)
);

CREATE TABLE douyin."VIDEO_LIKE" (
    user_id BIGINT NOT NULL,
    video_id BIGINT NOT NULL,
    liked_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (user_id, video_id),
    CONSTRAINT fk_video_like_user FOREIGN KEY (user_id) REFERENCES douyin."USER" (user_id),
    CONSTRAINT fk_video_like_video FOREIGN KEY (video_id) REFERENCES douyin."VIDEO" (video_id)
);

CREATE TABLE douyin."FOLLOW" (
    follower_id BIGINT NOT NULL,
    followed_id BIGINT NOT NULL,
    followed_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (follower_id, followed_id),
    CONSTRAINT fk_follow_follower FOREIGN KEY (follower_id) REFERENCES douyin."USER" (user_id),
    CONSTRAINT fk_follow_followed FOREIGN KEY (followed_id) REFERENCES douyin."USER" (user_id),
    CONSTRAINT ck_follow_not_self CHECK (follower_id <> followed_id)
);

CREATE TABLE douyin."COLLECTION" (
    collection_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    owner_id BIGINT NOT NULL,
    collection_name VARCHAR(100) COLLATE "C" NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (collection_id),
    CONSTRAINT uq_collection_owner_name UNIQUE (owner_id, collection_name),
    CONSTRAINT fk_collection_owner FOREIGN KEY (owner_id) REFERENCES douyin."USER" (user_id),
    CONSTRAINT ck_collection_name CHECK (CHAR_LENGTH(TRIM(collection_name)) > 0 AND OCTET_LENGTH(collection_name) = OCTET_LENGTH(TRIM(collection_name))),
    CONSTRAINT ck_collection_id CHECK (collection_id > 0)
);

CREATE TABLE douyin."COLLECTION_ITEM" (
    collection_id BIGINT NOT NULL,
    item_no INTEGER NOT NULL,
    video_id BIGINT NOT NULL,
    added_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (collection_id, item_no),
    CONSTRAINT uq_collection_item_video UNIQUE (collection_id, video_id),
    CONSTRAINT fk_collection_item_collection FOREIGN KEY (collection_id) REFERENCES douyin."COLLECTION" (collection_id),
    CONSTRAINT fk_collection_item_video FOREIGN KEY (video_id) REFERENCES douyin."VIDEO" (video_id),
    CONSTRAINT ck_collection_item_number CHECK (item_no > 0)
);

CREATE INDEX ix_video_creator_visibility_time ON douyin."VIDEO" (creator_id, visibility_status, published_at);

CREATE INDEX ix_video_music ON douyin."VIDEO" (music_id);

CREATE INDEX ix_comment_video_status_time ON douyin."COMMENT" (video_id, comment_status, created_at);

CREATE INDEX ix_comment_author ON douyin."COMMENT" (author_id);

CREATE INDEX ix_comment_parent ON douyin."COMMENT" (parent_comment_id);

CREATE INDEX ix_video_topic_topic ON douyin."VIDEO_TOPIC" (topic_id, video_id);

CREATE INDEX ix_video_like_video ON douyin."VIDEO_LIKE" (video_id, user_id);

CREATE INDEX ix_follow_followed ON douyin."FOLLOW" (followed_id, follower_id);

CREATE INDEX ix_collection_item_video ON douyin."COLLECTION_ITEM" (video_id, collection_id);

